#include "giopi.h"

// getdigits.c
void getdigits(char *input, unsigned long *result);
void getsplits(char *input, unsigned long *result);

// logging.c
void loginit(char *logfile, bool keeplog);
void logthis(char *filename, char *fmt, ...);
void logdone();

// split.c
void split(unsigned long b, unsigned long digits, unsigned long splits);

// tmptxt.c
void tmptxt(unsigned long digits, bool savevalue, bool rawoutput, bool gmpoutput, clock_t start_time, char *logfile, char *rawfile, char *txtfile);

// getopt_long structures
char          *short_options = "d:s:1248ngrh?";
struct option long_options[] = {
  {"digits",  required_argument,  0,  'd'},
  {"DIGITS",  required_argument,  0,  'd'},
  {"splits",  required_argument,  0,  's'},
  {"SPLITS",  required_argument,  0,  's'},
  {"noout",   no_argument,        0,  'n'},
  {"NOOUT",   no_argument,        0,  'n'},
  {"raw",     no_argument,        0,  'r'},
  {"RAW",     no_argument,        0,  'r'},
  {"gmp",     no_argument,        0,  'g'},
  {"GMP",     no_argument,        0,  'g'},
  {"help",    no_argument,        0,  'h'},
  {"HELP",    no_argument,        0,  'h'},
  {0,         0,                  0,  0}
};

void usage() {
  printf("giopi [-d/--digits] digits [-1/-2/-4/-8] [--splits splits] [-n] [--noout] [-r] [--raw] [-h] [--help]\n");
  printf("\n");
  printf("-d digits / --digits digits / digits\n");
  printf("  Desired digits (prompted if digits not specified)\n");
  printf("  (digit-only used in preference to others, otherwise last value specified used)\n");
  printf("\n");
  printf("-1 / -2 / -4 / -8 / --splits splits\n");
  printf("  Use 1/2/4/8 way version of the binary split (default = 2, any other value ignored)\n");
  printf("\n");
  printf("-n / --noout\n");
  printf("  Skip output file (useful for timing runs)\n");
  printf("\n");
  printf("-r / --raw\n");
  printf("  Generate raw output rather than text\n");
  printf("\n");
  printf("-h / --help\n");
  printf("  Print this help text\n");
}

int main(int argc, char *argv[]) {
  unsigned long digits, value, count, terms, bits, splits;
  char          logfile[NAMESIZE], rawfile[NAMESIZE], txtfile[NAMESIZE];
  clock_t       start_time, inter_time;
  bool          savevalue, rawoutput, gmpoutput;
  int           option, option_index;

  digits = 0;
  splits = 2;
  savevalue = true;
  rawoutput = false;
  gmpoutput = false;

  while((option = getopt_long(argc, argv, short_options, long_options, &option_index)) != -1) {
    switch(option) {
      case 'd':
        getdigits(optarg, &value);
        if (value > 0) { digits = value; }
        break;
      case 's':
        getsplits(optarg, &value);
        if (value > 0) { splits = value; }
        break;
      case '1':
        splits = 1;
        break;
      case '2':
        splits = 2;
        break;
      case '4':
        splits = 4;
        break;
      case '8':
        splits = 8;
        break;
      case 'n':
        savevalue = false;
        break;
      case 'r':
        rawoutput = true;
        break;
      case 'g':
        gmpoutput = true;
        break;
      case 'h':
      case '?':
      default:
        usage();
        return EXIT_SUCCESS;
    }
  }
  
  for ( ; optind < argc ; optind++) {
    getdigits(argv[optind], &value);
    if (value > 0) { digits = value; }
  }

  if (digits == 0) {
    printf("Digits? ");
    scanf("%lu", &digits);
    if (digits == 0) {
      printf("ERROR: Invalid digit count specified\n\n");
      usage();
      return EXIT_FAILURE;
    }
  }

  sprintf(logfile, "%lu.log", digits);
  sprintf(rawfile, "%lu.raw", digits);
  sprintf(txtfile, "%lu.txt", digits);
  loginit(logfile, false);

  terms = (digits / DIGITS_PER_ITER) + 1;
  bits = (digits * BITS_PER_DIGIT) + LEEWAY;
  mpf_set_default_prec(bits);

  logthis(logfile, "Build:  %s (%s - %s)\n", BUILDNAME, BUILDDATE, BUILDTYPE);
  logthis(logfile, "Digits: %lu\n", digits);
  logthis(logfile, "Terms:  %lu\n\n", terms);

  // binary split
  start_time = clock();
  logthis(NULL, "Split:\r");
  split(terms, digits, splits);
  logthis(logfile, "Split: (%lu) %9.2f seconds\n", splits, (double) (clock() - start_time) / CLOCKS_PER_SEC);

  // process pass-9-*.tmp files generated by split() for final result
  tmptxt(digits, savevalue, rawoutput, gmpoutput, start_time, logfile, rawfile, txtfile);

  // tidy up
  logdone();

  return EXIT_SUCCESS;
}
