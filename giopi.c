void loginit(char *logfile, bool keeplog);
void logthis(char *filename, char *fmt, ...);
void logdone();

// split.c
void split(unsigned long b, unsigned long digits, unsigned long splits);

// root10005.c
void root10005(mpf_t r, unsigned long digits);

